-- Phase 7 P7-13 (salary advances; design `PHASE7_PAYROLL_FUNDS.md` 4.4, OQ-110, P7-T12; Owner: nothing pays money without his click).
--
-- Additive: one new table (empty), one enum, and one nullable column on the (empty) payroll item table. An advance is requested by a person with
-- MANAGE_PAYROLL, approved and paid by a person with APPROVE_PAYROLL (paying needs a fresh password and writes the fund outflow in the same
-- transaction). It is recovered by `ADVANCE_RECOVERY` items of closed payroll runs, never by editing anything; what a closed run could not
-- take stays outstanding for the next one; the Owner may write the rest off with a reason. A person has at most one open advance, and an
-- advance never exceeds half the monthly base salary (checked by the application against the confirmed salary).

CREATE TYPE "SalaryAdvanceStatus" AS ENUM ('REQUESTED', 'APPROVED', 'PAID', 'RECOVERED', 'WRITTEN_OFF', 'CANCELLED');

CREATE TABLE "salary_advances" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "seq" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "employee_user_id" UUID NOT NULL,
    "amount_vnd" BIGINT NOT NULL,
    "status" "SalaryAdvanceStatus" NOT NULL DEFAULT 'REQUESTED',
    "reason" TEXT NOT NULL,
    "requested_by_user_id" UUID NOT NULL,
    "requested_at" TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
    "client_request_id" UUID NOT NULL,
    "approved_by_user_id" UUID,
    "approved_at" TIMESTAMPTZ(3),
    "paid_by_user_id" UUID,
    "paid_at" TIMESTAMPTZ(3),
    "paid_fund_id" UUID,
    "paid_entry_id" UUID,
    "cancelled_by_user_id" UUID,
    "cancelled_at" TIMESTAMPTZ(3),
    "cancel_reason" TEXT,
    "written_off_by_user_id" UUID,
    "written_off_at" TIMESTAMPTZ(3),
    "written_off_vnd" BIGINT,
    "write_off_reason" TEXT,
    "recovered_at" TIMESTAMPTZ(3),
    "row_version" INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT "salary_advances_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "salary_advances_amount" CHECK ("amount_vnd" > 0 AND "amount_vnd" <= 10000000000),
    CONSTRAINT "salary_advances_reason" CHECK (length(btrim("reason")) > 0),
    CONSTRAINT "salary_advances_shape" CHECK (
      ("status" = 'REQUESTED' AND "approved_at" IS NULL AND "paid_at" IS NULL AND "cancelled_at" IS NULL AND "written_off_at" IS NULL AND "recovered_at" IS NULL)
      OR ("status" = 'APPROVED' AND "approved_at" IS NOT NULL AND "approved_by_user_id" IS NOT NULL AND "paid_at" IS NULL AND "cancelled_at" IS NULL AND "written_off_at" IS NULL AND "recovered_at" IS NULL)
      OR ("status" = 'PAID' AND "paid_at" IS NOT NULL AND "paid_by_user_id" IS NOT NULL AND "paid_fund_id" IS NOT NULL AND "paid_entry_id" IS NOT NULL AND "cancelled_at" IS NULL AND "written_off_at" IS NULL AND "recovered_at" IS NULL)
      OR ("status" = 'RECOVERED' AND "paid_at" IS NOT NULL AND "recovered_at" IS NOT NULL AND "cancelled_at" IS NULL AND "written_off_at" IS NULL)
      OR ("status" = 'WRITTEN_OFF' AND "paid_at" IS NOT NULL AND "written_off_at" IS NOT NULL AND "written_off_by_user_id" IS NOT NULL AND "written_off_vnd" > 0
          AND length(btrim(coalesce("write_off_reason", ''))) > 0 AND "cancelled_at" IS NULL AND "recovered_at" IS NULL)
      OR ("status" = 'CANCELLED' AND "cancelled_at" IS NOT NULL AND "cancelled_by_user_id" IS NOT NULL AND length(btrim(coalesce("cancel_reason", ''))) > 0
          AND "paid_at" IS NULL AND "written_off_at" IS NULL AND "recovered_at" IS NULL)
    )
);
CREATE UNIQUE INDEX "salary_advances_seq_key" ON "salary_advances"("seq");
CREATE UNIQUE INDEX "salary_advances_request_key" ON "salary_advances"("requested_by_user_id", "client_request_id");
-- One open advance per person (OQ-110).
CREATE UNIQUE INDEX "salary_advances_one_open_key" ON "salary_advances"("employee_user_id") WHERE "status" IN ('REQUESTED', 'APPROVED', 'PAID');
CREATE UNIQUE INDEX "salary_advances_entry_key" ON "salary_advances"("paid_entry_id") WHERE "paid_entry_id" IS NOT NULL;
CREATE INDEX "salary_advances_employee_idx" ON "salary_advances"("employee_user_id", "seq");
CREATE INDEX "salary_advances_status_idx" ON "salary_advances"("status");
