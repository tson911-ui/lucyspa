-- An advance never moves backwards, never changes its person or amount, never forgets a stage it went through, and is never deleted.
CREATE FUNCTION lucy_guard_salary_advance() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A salary advance is history and is never deleted';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.status <> 'REQUESTED' THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A salary advance starts as a request';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.employee_user_id <> OLD.employee_user_id OR NEW.amount_vnd <> OLD.amount_vnd OR NEW.reason <> OLD.reason
     OR NEW.requested_by_user_id <> OLD.requested_by_user_id OR NEW.requested_at <> OLD.requested_at OR NEW.seq <> OLD.seq THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A salary advance keeps its person, amount and reason';
  END IF;
  IF NEW IS DISTINCT FROM OLD AND NEW.row_version <> OLD.row_version + 1 THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A salary advance change bumps the version by one';
  END IF;
  IF OLD.status <> NEW.status AND NOT (
       (OLD.status = 'REQUESTED' AND NEW.status IN ('APPROVED', 'CANCELLED'))
    OR (OLD.status = 'APPROVED' AND NEW.status IN ('PAID', 'CANCELLED'))
    OR (OLD.status = 'PAID' AND NEW.status IN ('RECOVERED', 'WRITTEN_OFF'))) THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A salary advance only moves forward';
  END IF;
  IF (OLD.approved_at IS NOT NULL AND (NEW.approved_at IS DISTINCT FROM OLD.approved_at OR NEW.approved_by_user_id IS DISTINCT FROM OLD.approved_by_user_id))
     OR (OLD.paid_at IS NOT NULL AND (NEW.paid_at IS DISTINCT FROM OLD.paid_at OR NEW.paid_by_user_id IS DISTINCT FROM OLD.paid_by_user_id
         OR NEW.paid_fund_id IS DISTINCT FROM OLD.paid_fund_id OR NEW.paid_entry_id IS DISTINCT FROM OLD.paid_entry_id))
     OR (OLD.cancelled_at IS NOT NULL AND NEW IS DISTINCT FROM OLD)
     OR (OLD.written_off_at IS NOT NULL AND NEW IS DISTINCT FROM OLD)
     OR (OLD.recovered_at IS NOT NULL AND NEW IS DISTINCT FROM OLD) THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A finished stage of a salary advance never changes';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER lucy_salary_advances_guard BEFORE INSERT OR UPDATE OR DELETE ON "salary_advances"
  FOR EACH ROW EXECUTE FUNCTION lucy_guard_salary_advance();

