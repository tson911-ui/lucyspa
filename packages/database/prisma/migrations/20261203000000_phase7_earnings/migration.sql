-- An earning is immutable; only `run_id` may be set, once, from NULL. A reversal must reverse an earning of the same employee, kind and
-- line, and all the reversals of one earning together never exceed it.
CREATE FUNCTION lucy_guard_pay_earning() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  original RECORD;
  reversed BIGINT;
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Earnings are history and are never deleted';
  END IF;
  IF TG_OP = 'UPDATE' THEN
    IF NEW.run_id IS NOT DISTINCT FROM OLD.run_id
       OR OLD.run_id IS NOT NULL
       OR (to_jsonb(NEW) - 'run_id') IS DISTINCT FROM (to_jsonb(OLD) - 'run_id') THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'An earning never changes; only the payroll run that claims it is set, once';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.reverses_id IS NOT NULL THEN
    SELECT id, kind, employee_user_id, invoice_id, invoice_line_id, paid_seq, amount_vnd, reverses_id INTO original
      FROM pay_earnings WHERE id = NEW.reverses_id;
    IF NOT FOUND OR original.reverses_id IS NOT NULL OR original.kind <> NEW.kind
       OR original.employee_user_id <> NEW.employee_user_id OR original.invoice_id <> NEW.invoice_id
       OR original.invoice_line_id <> NEW.invoice_line_id OR original.paid_seq <> NEW.paid_seq THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A reversal reverses one earning of the same person, kind, line and episode';
    END IF;
    SELECT COALESCE(SUM(-amount_vnd), 0) INTO reversed FROM pay_earnings WHERE reverses_id = NEW.reverses_id;
    IF reversed + (-NEW.amount_vnd) > original.amount_vnd THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Reversals never exceed the earning they reverse';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER lucy_pay_earnings_guard BEFORE INSERT OR UPDATE OR DELETE ON "pay_earnings"
  FOR EACH ROW EXECUTE FUNCTION lucy_guard_pay_earning();

