--
-- Additive: two new tables, both empty. `pay_earnings` holds the tour and product-commission amounts an employee has earned. A row is
-- born when an invoice is PAID (per paid episode, keyed by `source_key`), keeps the value it had when it was calculated (the rule, the
-- base and the result are stored), and is never edited: a payment reversal, a refund, an exchange or a change of seller adds a NEGATIVE
-- row that points at the earning (`reverses_id`). Only `run_id` may change, once, from NULL: the payroll run that claims the row
-- (the claim itself arrives with P7-12; the column carries no foreign key yet). `pay_seller_overrides` records an audited correction of
-- who sold a product line after finalization (the invoice line itself is never rewritten). Nothing is written by this migration and
-- nothing is earned until the Owner has started the cash book and payroll (`finance_go_live`).

CREATE TYPE "PayEarningKind" AS ENUM ('TOUR', 'PRODUCT_COMMISSION');

CREATE TABLE "pay_earnings" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "seq" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "kind" "PayEarningKind" NOT NULL,
    "employee_user_id" UUID NOT NULL,
    "branch_id" UUID NOT NULL,
    "invoice_id" UUID NOT NULL,
    "invoice_line_id" UUID NOT NULL,
    "paid_seq" INTEGER NOT NULL,
    "business_date" DATE NOT NULL,
    "amount_vnd" BIGINT NOT NULL,
    "base_vnd" BIGINT,
    "quantity" INTEGER,
    "rule_id" UUID,
    "rule_kind" VARCHAR(20),
    "rule_value" BIGINT,
    "reverses_id" UUID,
    "reason" VARCHAR(40),
    "source_key" TEXT NOT NULL,
    "run_id" UUID,
    "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT "pay_earnings_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "pay_earnings_amount_sign" CHECK (("reverses_id" IS NULL AND "amount_vnd" > 0) OR ("reverses_id" IS NOT NULL AND "amount_vnd" < 0)),
    CONSTRAINT "pay_earnings_amount_max" CHECK (abs("amount_vnd") <= 10000000000),
    CONSTRAINT "pay_earnings_paid_seq" CHECK ("paid_seq" >= 1),
    CONSTRAINT "pay_earnings_reason" CHECK (("reverses_id" IS NULL) = ("reason" IS NULL))
);
CREATE UNIQUE INDEX "pay_earnings_source_key" ON "pay_earnings"("source_key");
CREATE UNIQUE INDEX "pay_earnings_seq_key" ON "pay_earnings"("seq");
CREATE INDEX "pay_earnings_employee_date_idx" ON "pay_earnings"("employee_user_id", "business_date", "kind");
CREATE INDEX "pay_earnings_invoice_idx" ON "pay_earnings"("invoice_id", "invoice_line_id");
CREATE INDEX "pay_earnings_reverses_idx" ON "pay_earnings"("reverses_id");
CREATE INDEX "pay_earnings_run_idx" ON "pay_earnings"("run_id");
CREATE INDEX "pay_earnings_branch_date_idx" ON "pay_earnings"("branch_id", "business_date");
