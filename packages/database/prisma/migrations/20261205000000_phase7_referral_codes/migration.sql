-- Phase 7 P7-10b (staff referral codes; design `PHASE7_PAYROLL_FUNDS.md` section 14, P7-T16; Owner answer 3 of 2026-10-11: an online sale earns
-- commission only when the customer enters a staff member's referral code at checkout; the code is unique and stable, the Owner views and
-- resets it, an invalid or inactive code is rejected, and the code is stored on the order and cannot change after payment).
--
-- Additive: two new tables, both empty. No code is created by this migration (a code exists only after the Owner's click). The existing rule
-- "an online line has no seller" is untouched: the person who earns on an online line is named by `order_referrals`, not by the line.

CREATE TABLE "employee_referral_codes" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "seq" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "employee_user_id" UUID NOT NULL,
    "code" VARCHAR(12) NOT NULL,
    "is_active" BOOLEAN NOT NULL DEFAULT true,
    "created_by_user_id" UUID NOT NULL,
    "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
    "deactivated_at" TIMESTAMPTZ(3),
    "deactivated_by_user_id" UUID,
    "deactivation_reason" TEXT,
    CONSTRAINT "employee_referral_codes_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "employee_referral_codes_code_shape" CHECK ("code" ~ '^[A-Z2-9]{6,12}$' AND "code" !~ '[IO]'),
    CONSTRAINT "employee_referral_codes_state" CHECK (
      ("is_active" AND "deactivated_at" IS NULL AND "deactivated_by_user_id" IS NULL AND "deactivation_reason" IS NULL)
      OR (NOT "is_active" AND "deactivated_at" IS NOT NULL AND "deactivated_by_user_id" IS NOT NULL
          AND length(btrim(coalesce("deactivation_reason", ''))) > 0))
);
CREATE UNIQUE INDEX "employee_referral_codes_seq_key" ON "employee_referral_codes"("seq");
-- A code is never reused, not even after it was deactivated (history stays unambiguous).
CREATE UNIQUE INDEX "employee_referral_codes_code_key" ON "employee_referral_codes"("code");
CREATE UNIQUE INDEX "employee_referral_codes_one_active_key" ON "employee_referral_codes"("employee_user_id") WHERE "is_active";
CREATE INDEX "employee_referral_codes_employee_idx" ON "employee_referral_codes"("employee_user_id", "seq");
ALTER TABLE "employee_referral_codes" ADD CONSTRAINT "employee_referral_codes_employee_fkey" FOREIGN KEY ("employee_user_id")
  REFERENCES "employee_profiles"("user_id") ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE "employee_referral_codes" ADD CONSTRAINT "employee_referral_codes_creator_fkey" FOREIGN KEY ("created_by_user_id")
  REFERENCES "users"("id") ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE "employee_referral_codes" ADD CONSTRAINT "employee_referral_codes_deactivator_fkey" FOREIGN KEY ("deactivated_by_user_id")
  REFERENCES "users"("id") ON DELETE RESTRICT ON UPDATE RESTRICT;

-- A code row never changes, except that an active code is deactivated once (with who and why). Never deleted.
CREATE FUNCTION lucy_guard_referral_code() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Referral codes are history and are never deleted';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NOT NEW.is_active THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A referral code starts active';
    END IF;
    RETURN NEW;
  END IF;
  IF NOT OLD.is_active
     OR NEW.is_active
     OR (to_jsonb(NEW) - 'is_active' - 'deactivated_at' - 'deactivated_by_user_id' - 'deactivation_reason')
        IS DISTINCT FROM (to_jsonb(OLD) - 'is_active' - 'deactivated_at' - 'deactivated_by_user_id' - 'deactivation_reason') THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A referral code never changes; an active one can only be switched off, once';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER lucy_referral_codes_guard BEFORE INSERT OR UPDATE OR DELETE ON "employee_referral_codes"
  FOR EACH ROW EXECUTE FUNCTION lucy_guard_referral_code();

-- The code an online order was placed with. One per order, written once when the order is built, never changed or deleted (so it is
-- frozen from the start, and certainly after payment). It keeps the code text as entered by the customer and the person it named.
CREATE TABLE "order_referrals" (
    "invoice_id" UUID NOT NULL,
    "employee_user_id" UUID NOT NULL,
    "code_id" UUID NOT NULL,
    "code" VARCHAR(12) NOT NULL,
    "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT "order_referrals_pkey" PRIMARY KEY ("invoice_id")
);
CREATE INDEX "order_referrals_employee_idx" ON "order_referrals"("employee_user_id");
CREATE INDEX "order_referrals_code_idx" ON "order_referrals"("code_id");
ALTER TABLE "order_referrals" ADD CONSTRAINT "order_referrals_invoice_fkey" FOREIGN KEY ("invoice_id")
  REFERENCES "invoices"("id") ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE "order_referrals" ADD CONSTRAINT "order_referrals_employee_fkey" FOREIGN KEY ("employee_user_id")
  REFERENCES "employee_profiles"("user_id") ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE "order_referrals" ADD CONSTRAINT "order_referrals_code_fkey" FOREIGN KEY ("code_id")
  REFERENCES "employee_referral_codes"("id") ON DELETE RESTRICT ON UPDATE RESTRICT;

CREATE FUNCTION lucy_guard_order_referral() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  target RECORD;
  chosen RECORD;
BEGIN
  SELECT channel, status INTO target FROM invoices WHERE id = NEW.invoice_id;
  IF target.channel IS DISTINCT FROM 'ONLINE' OR target.status IS DISTINCT FROM 'DRAFT' THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A referral code belongs to an online order that is still being built';
  END IF;
  SELECT employee_user_id, code INTO chosen FROM employee_referral_codes WHERE id = NEW.code_id;
  IF NOT FOUND OR chosen.employee_user_id <> NEW.employee_user_id OR chosen.code <> NEW.code THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'The order referral must copy the code and the person it names';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER lucy_order_referrals_guard BEFORE INSERT ON "order_referrals"
  FOR EACH ROW EXECUTE FUNCTION lucy_guard_order_referral();
CREATE TRIGGER lucy_order_referrals_append_only BEFORE UPDATE OR DELETE ON "order_referrals"
  FOR EACH ROW EXECUTE FUNCTION lucy_refuse_change();
