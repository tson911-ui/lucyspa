-- A tip is immutable; only `run_id` is set, once. A reversal reverses one tip of the same invoice, person, method and branch, once, in full
-- (a mistaken amount is reversed and re-entered).
CREATE FUNCTION lucy_guard_tip() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  original RECORD;
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Tips are history and are never deleted';
  END IF;
  IF TG_OP = 'UPDATE' THEN
    IF NEW.run_id IS NOT DISTINCT FROM OLD.run_id
       OR OLD.run_id IS NOT NULL
       OR (to_jsonb(NEW) - 'run_id') IS DISTINCT FROM (to_jsonb(OLD) - 'run_id') THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A tip never changes; only the payroll run that pays it is set, once';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.reverses_id IS NOT NULL THEN
    SELECT id, branch_id, invoice_id, employee_user_id, method, amount_vnd, reverses_id, run_id INTO original
      FROM tips WHERE id = NEW.reverses_id;
    IF NOT FOUND OR original.reverses_id IS NOT NULL OR original.branch_id <> NEW.branch_id OR original.invoice_id <> NEW.invoice_id
       OR original.employee_user_id <> NEW.employee_user_id OR original.method <> NEW.method
       OR original.amount_vnd <> -NEW.amount_vnd THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A tip reversal undoes one tip of the same invoice, person and method, in full';
    END IF;
    IF original.run_id IS NOT NULL THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'A tip that a payroll run has taken cannot be reversed here';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER lucy_tips_guard BEFORE INSERT OR UPDATE OR DELETE ON "tips"
  FOR EACH ROW EXECUTE FUNCTION lucy_guard_tip();
