-- Phase 7 P7-10 (tips; design `PHASE7_PAYROLL_FUNDS.md` section 6; P7-T7; Owner answer 5 of 2026-10-11: tips are paid on the payroll payment day
-- and stay outside revenue, loyalty points and the commission base).
--
-- Additive: one new table, empty. A tip is a SEPARATE record: it is never part of an invoice or a payment (PayOS must match the invoice
-- amount, tips earn no points and are not revenue). It names the invoice, the KTV who served and the money the shop received (cash at
-- the counter, or a transfer the shop recorded); the matching fund entry (TIP_IN) is written by the same command. A tip is immutable: a
-- mistake is a NEGATIVE row that reverses it (and a reversing fund entry). Only `run_id` may change, once, from NULL: the payroll run
-- that pays the tip out together with the payslip (P7-12..P7-14; the column carries no foreign key yet).

CREATE TYPE "TipMethod" AS ENUM ('CASH', 'TRANSFER');

CREATE TABLE "tips" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "seq" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "branch_id" UUID NOT NULL,
    "invoice_id" UUID NOT NULL,
    "employee_user_id" UUID NOT NULL,
    "amount_vnd" BIGINT NOT NULL,
    "method" "TipMethod" NOT NULL,
    "business_date" DATE NOT NULL,
    "reverses_id" UUID,
    "reason" TEXT,
    "recorded_by_user_id" UUID NOT NULL,
    "client_request_id" UUID NOT NULL,
    "fund_entry_id" UUID NOT NULL,
    "run_id" UUID,
    "recorded_at" TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT "tips_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "tips_amount_sign" CHECK (("reverses_id" IS NULL AND "amount_vnd" > 0) OR ("reverses_id" IS NOT NULL AND "amount_vnd" < 0)),
    CONSTRAINT "tips_amount_max" CHECK (abs("amount_vnd") <= 10000000000),
    CONSTRAINT "tips_reason" CHECK (("reverses_id" IS NULL) OR length(btrim(coalesce("reason", ''))) > 0)
);
CREATE UNIQUE INDEX "tips_seq_key" ON "tips"("seq");
CREATE UNIQUE INDEX "tips_request_key" ON "tips"("recorded_by_user_id", "client_request_id");
CREATE UNIQUE INDEX "tips_reverses_key" ON "tips"("reverses_id") WHERE "reverses_id" IS NOT NULL;
CREATE INDEX "tips_invoice_idx" ON "tips"("invoice_id", "employee_user_id");
CREATE INDEX "tips_employee_idx" ON "tips"("employee_user_id", "business_date");
CREATE INDEX "tips_branch_date_idx" ON "tips"("branch_id", "business_date");
CREATE INDEX "tips_run_idx" ON "tips"("run_id");
CREATE INDEX "tips_fund_entry_idx" ON "tips"("fund_entry_id");
ALTER TABLE "tips" ADD CONSTRAINT "tips_branch_fkey" FOREIGN KEY ("branch_id")
  REFERENCES "branches"("id") ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE "tips" ADD CONSTRAINT "tips_invoice_fkey" FOREIGN KEY ("invoice_id")
  REFERENCES "invoices"("id") ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE "tips" ADD CONSTRAINT "tips_employee_fkey" FOREIGN KEY ("employee_user_id")
